import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// One source for CSS values and palette previews. Add future skins as role maps.
const root = new URL("../", import.meta.url);
const skin = JSON.parse(readFileSync(new URL("src/design-system/skins/emerald-night.json", root), "utf8"));
const declarations = Object.entries(skin.colors).map(([role, value]) => `  --${role}: ${value};`).join("\n");
const css = `/* Generated by scripts/sync-design-tokens.mjs. Edit skins/emerald-night.json. */
:root {
  --chrome: var(--muted-soft);
  --elevated: var(--paper-2);
  --input-surface: color-mix(in srgb, var(--canvas) 65%, var(--surface));
  --placeholder: var(--muted);
  --selected-foreground: var(--text);
  --primary-hover: color-mix(in srgb, var(--primary) 90%, white);
  --on-destructive: white;
  --on-match: var(--text);
  --success: var(--ayah);
  --scrim: #00000099;
}
.dark { --on-destructive: var(--on-primary); }
.dark:not([data-palette]), .dark[data-palette="default"] {
${declarations}
}
`;
const output = new URL("src/design-system/tokens.css", root);
writeFileSync(output, css);
console.log(`Generated ${fileURLToPath(output)}`);
